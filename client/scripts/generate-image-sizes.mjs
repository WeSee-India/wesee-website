// Regenerates client/src/data/imageSizes.ts from the real files in client/public.
// Run after adding or changing images:  node scripts/generate-image-sizes.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = "public";
const sizes = {};

(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isDirectory()) walk(file);
    else if (/\.(jpe?g|png|webp|gif)$/i.test(name)) {
      try {
        const out = execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0:s=x", file]).toString().trim();
        const [w, h] = out.split("x").map(Number);
        if (w && h) sizes["/" + path.relative(root, file).replace(/\\/g, "/")] = [w, h];
      } catch {
        // ffprobe missing or unreadable file: skip, the helper falls back to no dimensions
      }
    }
  }
})(root);

const body = Object.entries(sizes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, [w, h]]) => `  ${JSON.stringify(k)}: [${w}, ${h}],`)
  .join("\n");

fs.writeFileSync(
  "src/data/imageSizes.ts",
  `// Generated by scripts/generate-image-sizes.mjs. Do not edit by hand.\n/** Intrinsic [width, height] of each local image, keyed by its public URL path. */\nexport const imageSizes: Record<string, [number, number]> = {\n${body}\n};\n\n/** width/height attributes for a local image, so the browser reserves its space before it loads. Unknown or remote sources return {}. */\nexport function imgDims(src: string | undefined): { width?: number; height?: number } {\n  const size = src ? imageSizes[src] : undefined;\n  return size ? { width: size[0], height: size[1] } : {};\n}\n`,
);
console.log(`wrote ${Object.keys(sizes).length} sizes`);
